import { readFileSync, writeFileSync } from 'node:fs'
const sources = ['supabase/migrations/202610260001_initial_schema.sql','supabase/migrations/202610260002_accounts_and_login_audit.sql','supabase/upgrade.sql']
let sql = sources.map(path => readFileSync(path,'utf8')).join('\n\n')
// Make the known app policies repeatable without affecting unrelated policies.
sql = sql.replace(/create policy "([^"]+)"\s+on (public\.\w+)/g, (_,name,table) => `drop policy if exists "${name}" on ${table};\ncreate policy "${name}" on ${table}`)
writeFileSync('supabase/setup.sql', '-- Generated by npm run db:bundle. Paste this entire file into the SQL Editor.\n-- Review and apply only to the Supabase project for this application.\nbegin;\n\n'+sql+'\ncommit;\n')
console.log('Updated supabase/setup.sql')
